def rewrite_in_veles_tone(news_item: dict) -> dict:
    """
    Возвращает структурированный пост-словарь.
    Если есть Claude API — использует его. Иначе — шаблоны.
    """
    category = news_item.get("category", "general")

    # Дефолты, которые работают всегда
    default = {
        "hook": random.choice(CATEGORY_HOOKS.get(category, CATEGORY_HOOKS["general"])),
        "emoji": CATEGORY_EMOJI.get(category, "⚠️"),
        "category": category,
        "lead": news_item["summary"][:200],
        "lead_short": news_item["summary"][:120],
        "details": news_item["summary"][200:600] if len(news_item["summary"]) > 200 else (
            "Детали инцидента уточняются. По первым данным, атакующие действовали "
            "по типичной для этой категории схеме — без сложных инструментов, "
            "через известные точки входа."
        ),
        "context": (
            "Это часть тренда: подобные инциденты в этой категории стали "
            "в 2025–2026 происходить кратно чаще. По разным оценкам индустрии, "
            "удар получает каждый шестой средний бизнес в e-commerce за год."
        ),
        "consequences": CONSEQUENCES_BY_CATEGORY.get(category, CONSEQUENCES_BY_CATEGORY["general"]),
        "solution": random.choice(SOLUTION_BLOCKS),
        "source_link": news_item["link"],
        "fact_label": "минут на бесплатный аудит",
        "fact_value": "15",
        "attack_step_1": "нашли публично доступную уязвимость в админке",
        "attack_step_2": "подобрали слабый пароль из утёкших баз",
        "attack_step_3": "закрепились через забытую тестовую учётку",
    }

    if not USE_AI:
        return default

    # Пробуем через Claude. Если падает — откатываемся на шаблоны.
    try:
        ai_result = rewrite_with_claude(news_item, category)
        default.update({
            "hook": ai_result.get("hook", default["hook"]),
            "lead": ai_result.get("lead", default["lead"]),
            "details": ai_result.get("details", default["details"]),
            "context": ai_result.get("context", default["context"]),
            "consequences": ai_result.get("consequences", default["consequences"]),
            "solution": ai_result.get("solution", default["solution"]),
            "fact_label": ai_result.get("fact_label", default["fact_label"]),
            "fact_value": ai_result.get("fact_value", default["fact_value"]),
        })
        default["lead_short"] = default["lead"][:120]
        return default
    except Exception as e:
        print(f"[ai_writer] Claude error, using templates: {e}")
        return default
