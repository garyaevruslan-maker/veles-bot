def rewrite_with_claude(news_item: dict, category: str) -> dict:
    import anthropic
    client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY)
    user_text = (
        f"Категория: {category}\n"
        f"Заголовок оригинала: {news_item['title']}\n"
        f"Текст: {news_item['summary']}"
    )
    msg = client.messages.create(
        model="claude-haiku-4-5-20251001",
        max_tokens=2500,
        system=VELES_VOICE_PROMPT,
        messages=[{"role": "user", "content": user_text}]
    )
    text = msg.content[0].text.strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    return json.loads(text)


def rewrite_in_veles_tone(news_item: dict) -> dict:
    category = news_item.get("category", "general")
    summary = news_item.get("summary", "")
    title = news_item.get("title", "")
    seed = news_item.get("link", title or "x")

    # Заголовок — гибридный (из оригинала, fallback на шаблон)
    hook = _build_hook_from_title(title, category, seed)

    # Стабильно выбираем варианты по хешу — одна и та же новость = тот же текст
    consequences = _stable_choice(
        seed + "_cons",
        CONSEQUENCES_BY_CATEGORY.get(category, CONSEQUENCES_BY_CATEGORY["general"])
    )
    solution = _stable_choice(seed + "_sol", SOLUTION_BLOCKS)
    fact_label, fact_value = _stable_choice(seed + "_fact", FACT_POOL)
    context = _stable_choice(seed + "_ctx", CONTEXT_VARIANTS)

    lead, details_part = _split_summary(summary)
    if not details_part:
        details_part = (
            "Детали инцидента уточняются. По первым данным, атакующие "
            "действовали по типичной для этой категории схеме — без сложных "
            "инструментов, через известные точки входа. Реальные жертвы — "
            "не крупный бизнес, а средний и малый: им хуже всего обнаружить "
            "компрометацию."
        )

    default = {
        "hook": hook,
        "emoji": CATEGORY_EMOJI.get(category, "⚠️"),
        "category": category,
        "lead": lead or summary[:200],
        "lead_short": (lead or summary)[:120],
        "details": details_part,
        "context": context,
        "consequences": consequences,
        "solution": solution,
        "source_link": news_item["link"],
        "fact_label": fact_label,
        "fact_value": fact_value,
        "attack_step_1": "нашли публично доступную уязвимость в админке",
        "attack_step_2": "подобрали слабый пароль из утёкших баз",
        "attack_step_3": "закрепились через забытую тестовую учётку",
    }

    if not USE_AI:
        return default

    try:
        ai_result = rewrite_with_claude(news_item, category)
        for key in ("hook", "lead", "details", "context", "consequences",
                    "solution", "fact_label", "fact_value",
                    "attack_step_1", "attack_step_2", "attack_step_3"):
            if key in ai_result:
                default[key] = ai_result[key]
        default["lead_short"] = default["lead"][:120]
        return default
    except Exception as e:
        print(f"[ai_writer] Claude err, using templates: {e}")
        return default
