def _split_summary(summary: str):
    """Бьём summary на 3 блока: лид, детали, контекст."""
    sentences = [s.strip() for s in summary.replace("\n", " ").split(". ") if s.strip()]
    if not sentences:
        return summary, "", ""

    lead = ". ".join(sentences[:2])
    if not lead.endswith("."):
        lead += "."

    details_sentences = sentences[2:7] if len(sentences) > 2 else []
    details = ". ".join(details_sentences)
    if details and not details.endswith("."):
        details += "."

    return lead, details, ""


def _stable_choice(seed: str, options: list):
    """Выбор из списка, стабильный для одной и той же новости."""
    if not options:
        return None
    h = int(hashlib.md5(seed.encode()).hexdigest(), 16)
    return options[h % len(options)]


