def _split_summary(summary: str):
    sentences = [s.strip() for s in summary.replace("\n", " ").split(". ") if s.strip()]
    if not sentences:
        return summary, ""
    lead = ". ".join(sentences[:2])
    if not lead.endswith("."):
        lead += "."
    details_sentences = sentences[2:7] if len(sentences) > 2 else []
    details = ". ".join(details_sentences)
    if details and not details.endswith("."):
        details += "."
    return lead, details


def _stable_choice(seed: str, options: list):
    if not options:
        return None
    h = int(hashlib.md5(seed.encode()).hexdigest(), 16)
    return options[h % len(options)]


def _build_hook_from_title(title: str, category: str, seed: str) -> str:
    """
    Строим заголовок ИЗ ОРИГИНАЛА новости, а не из шаблона.
    Если оригинал короткий и ясный — используем его.
    Если длинный — обрезаем + добавляем эмодзи через категорию.
    Если плохой — fallback на шаблон.
    """
    title = (title or "").strip()
    if not title:
        return _stable_choice(seed + "_hook", CATEGORY_HOOKS.get(category, CATEGORY_HOOKS["general"]))

    # Убираем стандартные префиксы вроде "Breaking:" или "[CVE-2025-...]"
    cleanup_prefixes = ["breaking:", "update:", "alert:", "exclusive:"]
    title_lower = title.lower()
    for pref in cleanup_prefixes:
        if title_lower.startswith(pref):
            title = title[len(pref):].strip()
            break

    # Убираем CVE из конца
    if "cve-" in title.lower():
        idx = title.lower().find("cve-")
        title = title[:idx].rstrip(" -—:|").strip()
        if not title:
            return _stable_choice(seed + "_hook", CATEGORY_HOOKS.get(category, CATEGORY_HOOKS["general"]))

    # Если слишком длинный — обрезаем по последнему знаку препинания до 80 символов
    if len(title) > 90:
        cut = title[:90]
        for sep in [". ", "! ", "? ", " — ", " - ", ": "]:
            if sep in cut:
                cut = cut[:cut.rfind(sep)]
                break
        title = cut.strip()

    return title


