def rewrite_with_claude(news_item: dict, category: str) -> dict:
    """Живая переписка через Claude API."""
    import anthropic
    client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY)

    user_text = (
        f"Категория: {category}\n"
        f"Заголовок оригинала: {news_item['title']}\n"
        f"Текст: {news_item['summary']}"
    )

    msg = client.messages.create(
        # Haiku 4.5 ($1/$5 за 1M токенов) — отлично для перефраза.
        # Для премиум-качества меняй на "claude-opus-4-7" ($5/$25).
        model="claude-haiku-4-5-20251001",
        max_tokens=2000,
        system=VELES_VOICE_PROMPT,
        messages=[{"role": "user", "content": user_text}]
    )
    text = msg.content[0].text.strip()

    # Сносим возможную markdown-обёртку ```json ... ```
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()

    return json.loads(text)


